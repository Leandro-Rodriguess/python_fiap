# Questão 3

# Faça um programa em Python que solicite ao usuário a largura e o comprimento de um terreno,

# ambos em metros. Em seguida

# calcule e mostre na tela a área total do terreno em metros quadrados.



largura = float(input('Digite a largura do terreno: '))
comprimento = float(input('Digite o comprimento do terreno: '))

area = largura * comprimento

print(f'A área do terreno é {area} metros quadrados')
